# The inline ExternalOdometryData from a buffer flatc built out of
# fbs/state.fbs. Distinctive values, all exactly representable as float32.
REFERENCE_EXTERNAL_POSE = bytes.fromhex(
    "cb04fb711f0100000000c03f000010c0"
    "000048400000003f0000803e000000be"
    "0000803d00002841000034c100004241"
    "0000403f000000bf0000803e07012a03"
)
REFERENCE_VALUES = dict(
    timestamp_us=1234567890123,
    position=(1.5, -2.25, 3.125),
    quat=(0.5, 0.25, -0.125, 0.0625),
    velocity=(10.5, -11.25, 12.125),
    flags=7, status=1, source_id=42, id=3,
)


def cmd_selftest() -> int:
    failures = 0

    def check(label, got, want):
        nonlocal failures
        ok = got == want
        failures += not ok
        print(f"{'ok  ' if ok else 'FAIL'} {label}")
        if not ok:
            print(f"      got  {got}\n      want {want}")

    check("schema set hash matches the firmware pin",
          topic_catalog.SCHEMA_SET_HASH, FIRMWARE_SCHEMA_SET_HASH)

    for key, size in (("external_pose", 64), ("odom", 72), ("pose", 40),
                      ("pose_raw", 40), ("external_pose_cov", 328)):
        check(f"{key} payload size", topic_catalog.topic_by_key(key).payload_size, size)

    # The decoder, against a buffer this script did not produce.
    sample = _decode_external_pose(REFERENCE_EXTERNAL_POSE, None)
    check("reference buffer decodes", sample is not None, True)
    if sample is not None:
        check("reference timestamp", sample.timestamp_us, REFERENCE_VALUES["timestamp_us"])
        check("reference position", (sample.east, sample.north, sample.up),
              REFERENCE_VALUES["position"])
        check("reference attitude", sample.quat, REFERENCE_VALUES["quat"])
        check("reference velocity", sample.velocity_enu, REFERENCE_VALUES["velocity"])
        check("reference not lost or degraded", (sample.lost, sample.degraded), (False, False))

    check("reference instance filter rejects a mismatch",
          _decode_external_pose(REFERENCE_EXTERNAL_POSE, 99), None)
    check("reference instance filter accepts a match",
          _decode_external_pose(REFERENCE_EXTERNAL_POSE, 3) is not None, True)

    # The simulation packer, round-tripped through the schema decoder. If the
    # hand-written format string above were wrong, this is what would catch it.
    check("simulated payload is one payload_size", SIM_EXTERNAL_ODOMETRY.size, 64)
    sim = _decode_external_pose(simulate_payload(0.0, 4.0, 20.0, 5), 5)
    check("simulated payload decodes", sim is not None, True)
    if sim is not None:
        check("simulated position", (round(sim.east, 4), round(sim.north, 4), round(sim.up, 4)),
              (4.0, 0.0, 1.5))
        check("simulated velocity is tangential",
              round(sim.velocity_enu[0], 4) == 0.0 and sim.velocity_enu[1] > 0.0, True)

    # A producer that keeps publishing a position while reporting Lost has to
    # survive decoding as a sample, not be dropped: dropping it would leave the
    # downgrade to the staleness timeout instead of taking effect at once.
    lost_wire = _decode_external_pose(
        simulate_payload(0.0, 4.0, 20.0, 0,
                         flags=ExternalOdometryFlags.PositionValid | ExternalOdometryFlags.Lost,
                         status=ExternalOdometryStatus.Lost), None)
    check("a Lost producer sample decodes as lost",
          lost_wire is not None and lost_wire.lost, True)

    # Covariance indexing, checked against a direct enumeration of the triangle.
    rows, idx = [], 0
    for i in range(_COV_N):
        rows.append(idx)
        idx += _COV_N - i
    check("upper triangle has 78 elements", idx, 78)
    check("position variance indices", (COV_IDX_EAST, COV_IDX_NORTH, COV_IDX_UP),
          (rows[6], rows[7], rows[8]))

    # End to end: a sample becomes a frame the ground decoder accepts back.
    args = argparse.Namespace(
        yaw_offset=0.0, heading_offset=0.0, publish_yaw=False, origin_lat=40.0,
        origin_lon=-86.0, origin_alt=0.0, hdop=0.3, vdop=0.4, satellites=14,
        hacc=0.05, vacc=0.08, degraded_scale=4.0, gnss_instance=0)
    fix, *_ = sample_to_fix(sample, None, args, 0.0)
    check("fix from reference sample is 3d", fix.fix_type, GnssFixType.Fix3d)
    frames = FrameDecoder().feed(encode_frame(TOPIC_GNSS_FIX, fix.pack(), 7))
    check("round trip through the serial framing",
          [(t, s, len(p)) for t, s, p in frames], [(TOPIC_GNSS_FIX, 7, 64)])

    lost = PoseSample(0, 1.0, 2.0, 3.0, lost=True)
    lost_fix, *_ = sample_to_fix(lost, None, args, 0.0)
    check("a lost sample reports NoFix", lost_fix.fix_type, GnssFixType.NoFix)
    check("a lost sample saturates accuracy", lost_fix.horizontal_accuracy_mm, 65535)

    degraded = PoseSample(0, 1.0, 2.0, 3.0, degraded=True)
    deg_fix, *_ = sample_to_fix(degraded, None, args, 0.0)
    check("a degraded sample inflates accuracy",
          deg_fix.horizontal_accuracy_mm, int(round(args.hacc * 4.0 * 1000)))

    print("FAILED" if failures else "all checks passed")
    return 1 if failures else 0


