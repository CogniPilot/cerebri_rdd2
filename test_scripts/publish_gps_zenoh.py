"""
publish_gps_zenoh.py
====================
Bridge synapse FlatBuffers pose/odometry from Zenoh onto the vehicle as a GNSS
fix over the SiK telemetry radio.

``publish_gps_synapse.py`` takes its input from ROS 2 (``nav_msgs/Odometry``).
This one takes it from the synapse wire format itself: the fixed-layout payload
structs that https://github.com/CogniPilot/synapse_fbs defines and that a mocap
bridge publishes on Zenoh under ``[<namespace>/]<key>[/<instance>]``.

What goes *out* is unchanged -- the same bare 64-byte ``GnssFixData`` in the
same compact serial framing -- so the vehicle side, the ``-S mocap-gnss``
requirement and the calibrated ``origin_*`` / ``yaw_offset`` values all carry
over unchanged from the ROS script.

Input topics (``--topic``), all named by their synapse catalog key:

    external_pose  ExternalOdometryData  the estimator-input contract a mocap
                                         bridge writes into the vehicle's
                                         namespace; carries velocity and a
                                         tracking status. The default.
    odom           OdometryData          a filtered estimate, same content
    pose           PoseData              filtered pose, no velocity
    pose_raw       RawPoseData           unfiltered source pose, no velocity
    mocap          MocapPoseFrame        raw mocap frame; --instance selects
                                         which rigid body

There is no ``frame`` parameter here, unlike the ROS script. The synapse types
name their frame in the field itself (``position_enu_m``,
``angular_velocity_flu_rad_s``), and the README requires bridges to transform
before publishing, so the input is ENU by contract and cannot be FLU.

Usage
-----
    ./publish_gps_zenoh.py --port /dev/ttyUSB0
    ./publish_gps_zenoh.py --port /dev/ttyUSB0 --namespace cub1 --instance 0
    ./publish_gps_zenoh.py --topic mocap --instance 7 --dry-run
    ./publish_gps_zenoh.py --simulate --dry-run     # no mocap and no radio
    ./publish_gps_zenoh.py --selftest               # no zenoh needed
    ./publish_gps_zenoh.py --list-topics

Requirements
------------
    pip install eclipse-zenoh synapse-fbs pyserial

Check it landed, on the vehicle shell:

    csyn topic echo gnss
    csyn_serial status
"""

