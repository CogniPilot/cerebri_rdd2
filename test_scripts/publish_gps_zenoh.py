# ──────────────────────────────────────────────────────────────────────────────
# Normalised sample
# ──────────────────────────────────────────────────────────────────────────────
@dataclass
class PoseSample:
    """One decoded input sample, reduced to what a GNSS fix can carry."""

    timestamp_us: int
    east: float
    north: float
    up: float
    quat: Optional[Tuple[float, float, float, float]] = None      # w, x, y, z
    velocity_enu: Optional[Tuple[float, float, float]] = None     # ve, vn, vu
    lost: bool = False
    degraded: bool = False
    status: str = ""


def _enum_names(cls) -> dict:
    return {v: k for k, v in vars(cls).items() if not k.startswith("_")}


def _status_name(cls, value: int) -> str:
    return _enum_names(cls).get(value, f"status{value}")


FIX_TYPE_NAMES = _enum_names(GnssFixType) if HAVE_SYNAPSE_FBS else {}


# ExternalOdometryFlags and OdometryFlags declare the same eight bits in the
# same order, and ExternalOdometryStatus and OdometryStatus the same seven
# values, so one set of helpers covers both families. --selftest does not check
# that, because a divergence would be a schema change: the sizes and the schema
# set hash it does check would move with it.
def _flags_lost(flags: int) -> bool:
    return bool(flags & ExternalOdometryFlags.Lost)


def _flags_degraded(flags: int) -> bool:
    return bool(flags & (ExternalOdometryFlags.Extrapolated
                         | ExternalOdometryFlags.OutlierRejected
                         | ExternalOdometryFlags.Degraded))


def _status_lost(status: int) -> bool:
    return status == ExternalOdometryStatus.Lost


def _status_degraded(status: int) -> bool:
    return status in (ExternalOdometryStatus.ExtrapolatedShort,
                      ExternalOdometryStatus.ExtrapolatedLong,
                      ExternalOdometryStatus.OutlierRejected,
                      ExternalOdometryStatus.Degraded)


# ──────────────────────────────────────────────────────────────────────────────
# Decoders, one per input topic
# ──────────────────────────────────────────────────────────────────────────────
def _decode_external_pose(payload: bytes, instance: Optional[int],
                          ignore_flags: bool = False) -> Optional[PoseSample]:
    data = ExternalOdometryData()
    data.Init(bytearray(payload), 0)
    if instance is not None and data.Id() != instance:
        return None

    flags = data.Flags()
    if not flags & ExternalOdometryFlags.PositionValid and not ignore_flags:
        return None

    pos = data.PositionEnuM(Vec3f())
    sample = PoseSample(
        timestamp_us=data.TimestampUs(),
        east=pos.X(), north=pos.Y(), up=pos.Z(),
        lost=_flags_lost(flags) or _status_lost(data.Status()),
        degraded=_flags_degraded(flags) or _status_degraded(data.Status()),
        status=_status_name(ExternalOdometryStatus, data.Status()),
    )
    if flags & ExternalOdometryFlags.AttitudeValid or ignore_flags:
        q = data.Attitude(Quaternionf())
        sample.quat = (q.W(), q.X(), q.Y(), q.Z())
    if flags & ExternalOdometryFlags.LinearVelocityValid or ignore_flags:
        v = data.LinearVelocityEnuMS(Vec3f())
        sample.velocity_enu = (v.X(), v.Y(), v.Z())
    return sample


def _decode_odom(payload: bytes, instance: Optional[int],
                 ignore_flags: bool = False) -> Optional[PoseSample]:
    del instance  # OdometryData is single-instance; the key carries no id.
    data = OdometryData()
    data.Init(bytearray(payload), 0)

    flags = data.Flags()
    if not flags & ExternalOdometryFlags.PositionValid and not ignore_flags:
        return None

    pose = data.Pose(Posef())
    pos = pose.PositionEnuM(Vec3f())
    sample = PoseSample(
        timestamp_us=data.TimestampUs(),
        east=pos.X(), north=pos.Y(), up=pos.Z(),
        lost=_flags_lost(flags) or _status_lost(data.Status()),
        degraded=_flags_degraded(flags) or _status_degraded(data.Status()),
        status=_status_name(ExternalOdometryStatus, data.Status()),
    )
    if flags & ExternalOdometryFlags.AttitudeValid or ignore_flags:
        q = pose.Attitude(Quaternionf())
        sample.quat = (q.W(), q.X(), q.Y(), q.Z())
    if flags & ExternalOdometryFlags.LinearVelocityValid or ignore_flags:
        v = data.Twist(Twistf()).LinearVelocityEnuMS(Vec3f())
        sample.velocity_enu = (v.X(), v.Y(), v.Z())
    return sample


def _decode_pose_like(cls):
    """PoseData and RawPoseData differ only in name: timestamp plus a Posef."""

    def decode(payload: bytes, instance: Optional[int],
               ignore_flags: bool = False) -> Optional[PoseSample]:
        del instance, ignore_flags  # neither type carries validity bits
        data = cls()
        data.Init(bytearray(payload), 0)
        pose = data.Pose(Posef())
        pos = pose.PositionEnuM(Vec3f())
        q = pose.Attitude(Quaternionf())
        # Neither type carries validity bits, so there is nothing to gate on:
        # a sample on the topic is the producer asserting the pose is good.
        return PoseSample(
            timestamp_us=data.TimestampUs(),
            east=pos.X(), north=pos.Y(), up=pos.Z(),
            quat=(q.W(), q.X(), q.Y(), q.Z()),
        )

    return decode


def _decode_mocap(payload: bytes, instance: Optional[int],
                  ignore_flags: bool = False) -> Optional[PoseSample]:
    """Pick one rigid body out of a raw mocap frame.

    mocap.fbs calls MocapPoseFrame a debugging and bridge-level type and points
    estimators at ExternalOdometry instead, so this path exists for the case
    where no bridge is running yet and the mocap source is all there is.
    """
    frame = MocapPoseFrame.GetRootAs(bytearray(payload), 0)
    count = frame.RigidBodiesLength()
    if count == 0:
        return None

    body = None
    if instance is None:
        body = frame.RigidBodies(0)
    else:
        for i in range(count):
            candidate = frame.RigidBodies(i)
            if candidate.Id() == instance:
                body = candidate
                break
    if body is None:
        return None
    if not body.Flags() & MocapRawFlags.Valid and not ignore_flags:
        return None

    pose = body.Pose(Posef())
    pos = pose.PositionEnuM(Vec3f())
    q = pose.Attitude(Quaternionf())
    return PoseSample(
        timestamp_us=frame.TimestampUs(),
        east=pos.X(), north=pos.Y(), up=pos.Z(),
        quat=(q.W(), q.X(), q.Y(), q.Z()),
        status=f"rigid_body{body.Id()}",
    )


@dataclass(frozen=True)
class InputTopic:
    key: str
    decode: Callable[[bytes, Optional[int]], Optional[PoseSample]]
    note: str


def input_topics() -> dict:
    return {
        "external_pose": InputTopic("external_pose", _decode_external_pose,
                                    "estimator input from a mocap bridge"),
        "odom": InputTopic("odom", _decode_odom, "filtered estimate"),
        "pose": InputTopic("pose", _decode_pose_like(PoseData), "filtered pose, no velocity"),
        "pose_raw": InputTopic("pose_raw", _decode_pose_like(RawPoseData),
                               "unfiltered source pose, no velocity"),
        "mocap": InputTopic("mocap", _decode_mocap, "raw mocap frame, --instance picks a body"),
    }


# ──────────────────────────────────────────────────────────────────────────────
# Optional accuracy from the covariance companion topic
# ──────────────────────────────────────────────────────────────────────────────
# ExternalOdometryCovarianceData holds the upper triangle of the 12D tangent
# state [theta, velocity, position, angular_velocity], row-major. Row i of an
# n=12 upper triangle starts at i*n - i*(i-1)/2, and position is rows 6..8, so
# the three position variances are elements 57, 63 and 68.
_COV_N = 12


def _tri_diag(i: int, n: int = _COV_N) -> int:
    return i * n - i * (i - 1) // 2


COV_IDX_EAST = _tri_diag(6)
COV_IDX_NORTH = _tri_diag(7)
COV_IDX_UP = _tri_diag(8)


def decode_covariance(payload: bytes, instance: Optional[int]):
    """Return (timestamp_us, h_acc_m, v_acc_m) or None."""
    data = ExternalOdometryCovarianceData()
    data.Init(bytearray(payload), 0)
    if instance is not None and data.Id() != instance:
        return None

    cov = data.Covariance(CovarianceUpperTriangle78f())
    var_e = getattr(cov, f"C{COV_IDX_EAST}")()
    var_n = getattr(cov, f"C{COV_IDX_NORTH}")()
    var_u = getattr(cov, f"C{COV_IDX_UP}")()
    if var_e < 0.0 or var_n < 0.0 or var_u < 0.0:
        return None
    return data.TimestampUs(), math.sqrt(var_e + var_n), math.sqrt(var_u)


# ──────────────────────────────────────────────────────────────────────────────
# Sample -> GnssFix
# ──────────────────────────────────────────────────────────────────────────────
def sample_to_fix(sample: PoseSample, prev, args, boot_us: float, accuracy=None):
    """Convert one PoseSample into a GnssFix.

    ``prev`` is (east, north, up, monotonic) from the previous send, used only
    to difference a velocity when the input carries none. Returns
    (fix, east, north, up, vn, ve, vd, yaw_deg).
    """
    east, north, up = sample.east, sample.north, sample.up

    # Rotate the facility frame onto true north. Identical to the ROS script,
    # so a yaw_offset trimmed there is still correct here.
    if args.yaw_offset != 0.0:
        east, north = rotate_2d(east, north, args.yaw_offset)

    have_velocity = False
    ve = vn = vd = 0.0
    if sample.velocity_enu is not None:
        ve, vn, vu = sample.velocity_enu
        # Velocity lives in the same facility frame as position, so it takes
        # the same rotation. The ROS script gets this for free by differencing
        # already-rotated positions.
        if args.yaw_offset != 0.0:
            ve, vn = rotate_2d(ve, vn, args.yaw_offset)
        vd = -vu
        have_velocity = True
    elif prev is not None:
        dt = time.monotonic() - prev[3]
        if dt > 0.001:
            ve = (east - prev[0]) / dt
            vn = (north - prev[1]) / dt
            vd = -(up - prev[2]) / dt
            have_velocity = True

    yaw_deg = None
    if sample.quat is not None:
        w, x, y, z = sample.quat
        yaw_deg = (quaternion_to_yaw(x, y, z, w) + args.heading_offset) % 360.0

    if sample.lost:
        fix_type = GnssFixType.NoFix
        h_acc, v_acc = ACCURACY_UNUSABLE_M, ACCURACY_UNUSABLE_M
    else:
        fix_type = GnssFixType.Fix3d
        if accuracy is not None:
            h_acc, v_acc = accuracy
        else:
            h_acc, v_acc = args.hacc, args.vacc
        if sample.degraded:
            h_acc *= args.degraded_scale
            v_acc *= args.degraded_scale

    fix = build_gnss_fix(
        east, north, up, vn, ve, vd,
        args.origin_lat, args.origin_lon, args.origin_alt,
        boot_us=boot_us,
        yaw_deg=yaw_deg if args.publish_yaw else None,
        hdop=args.hdop, vdop=args.vdop, satellites=args.satellites,
        fix_type=fix_type, h_acc_m=h_acc, v_acc_m=v_acc,
        instance=args.gnss_instance, have_velocity=have_velocity,
    )
    return fix, east, north, up, vn, ve, vd, yaw_deg


# ──────────────────────────────────────────────────────────────────────────────
# Bridge
# ──────────────────────────────────────────────────────────────────────────────
class Bridge:
    def __init__(self, args):
        self.args = args
        self.topic = input_topics()[args.topic]
        self.lock = threading.Lock()
        self.sample = None
        self.sample_at = 0.0
        self.accuracy = None
        self.accuracy_at = 0.0
        self.decode_errors = 0
        self.arrived = 0
        self.dropped = 0
        self.last_arrival = None
        self.received = 0
        self.sent = 0
        self.seq = 0
        self.matched_key = None
        self.start = time.monotonic()
        self.prev = None
        self.link = None
        self.decoder = FrameDecoder()
        self.from_vehicle = {}
        self.read_error_logged = False

        if not args.dry_run:
            self._open_serial()

    # ── serial ───────────────────────────────────────────────────────────────
    def _open_serial(self):
        try:
            import serial
        except ImportError:
            sys.exit("pyserial is required unless --dry-run: pip install pyserial")
        try:
            self.link = serial.Serial(self.args.port, self.args.baud, timeout=0)
        except Exception as exc:
            sys.exit(f"cannot open {self.args.port}: {exc}")
        print(f"radio: {self.args.port} @ {self.args.baud}")

    # ── zenoh callbacks ──────────────────────────────────────────────────────
    def on_sample(self, sample):
        payload = _payload_bytes(sample)
        # Counted before the decode, so a topic that arrives but is rejected
        # can be told apart from one that never arrives at all. Those two look
        # identical from the outside and have nothing in common as faults.
        with self.lock:
            self.arrived += 1
            self.last_arrival = (str(sample.key_expr), len(payload))
        try:
            decoded = self.topic.decode(payload, self.args.instance, self.args.ignore_flags)
        except Exception as exc:
            self.decode_errors += 1
            if self.decode_errors == 1:
                print(f"decode failed on {sample.key_expr} ({len(payload)} B): {exc}",
                      file=sys.stderr)
            return
        if decoded is None:
            with self.lock:
                self.dropped += 1
            return
        with self.lock:
            self.sample = decoded
            self.sample_at = time.monotonic()
            self.received += 1
            self.matched_key = str(sample.key_expr)

    def on_covariance(self, sample):
        try:
            decoded = decode_covariance(_payload_bytes(sample), self.args.instance)
        except Exception:
            return
        if decoded is None:
            return
        with self.lock:
            self.accuracy = (decoded[1], decoded[2])
            self.accuracy_at = time.monotonic()

    def offer(self, decoded: PoseSample):
        """Inject a sample directly, for --simulate."""
        with self.lock:
            self.sample = decoded
            self.sample_at = time.monotonic()
            self.received += 1
            self.matched_key = "(simulated)"

    # ── periodic send ────────────────────────────────────────────────────────
    def tick(self):
        self._drain_vehicle()
        now = time.monotonic()

        with self.lock:
            sample = self.sample
            age = now - self.sample_at
            accuracy = self.accuracy if now - self.accuracy_at < self.args.timeout else None
            key = self.matched_key

        if sample is None:
            return None
        if age > self.args.timeout:
            # A frozen position sent at full confidence is worse than no fix at
            # all: the estimator has no way to tell it is stale. Say so instead.
            sample = PoseSample(sample.timestamp_us, sample.east, sample.north, sample.up,
                                lost=True, status=f"stale {age:.1f}s")
            accuracy = None

        boot_us = (now - self.start) * 1e6
        fix, east, north, up, vn, ve, vd, yaw = sample_to_fix(
            sample, self.prev, self.args, boot_us, accuracy)
        self.prev = (east, north, up, now)

        if self.link is not None:
            try:
                self.link.write(encode_frame(TOPIC_GNSS_FIX, fix.pack(), self.seq))
            except Exception as exc:
                print(f"serial write failed: {exc}", file=sys.stderr)
        self.seq = (self.seq + 1) & 0xFF
        self.sent += 1
        return sample, fix, east, north, up, vn, ve, vd, yaw, key

    def _drain_vehicle(self):
        if self.link is None:
            return
        try:
            waiting = self.link.in_waiting
            if not waiting:
                return
            for topic_id, _seq, _payload in self.decoder.feed(self.link.read(waiting)):
                name = TOPIC_NAMES.get(topic_id, f"id{topic_id}")
                self.from_vehicle[name] = self.from_vehicle.get(name, 0) + 1
        except Exception as exc:
            if not self.read_error_logged:
                print(f"serial read failed: {exc}", file=sys.stderr)
                self.read_error_logged = True

    def waiting_line(self, key: str) -> str:
        with self.lock:
            arrived, dropped, last = self.arrived, self.dropped, self.last_arrival
        if arrived == 0:
            return (f"nothing arriving on {key} -- check --connect and the key; "
                    "zenoh_scan.py lists what is actually publishing")
        return (f"{arrived} samples on {last[0]} ({last[1]} B), all {dropped} rejected: "
                "validity flags clear, or filtered out by --instance. "
                "--ignore-flags accepts them regardless.")

    def status_line(self, result) -> str:
        sample, fix, east, north, up, vn, ve, vd, yaw, key = result
        back = ", ".join(f"{k}={v}" for k, v in sorted(self.from_vehicle.items()))
        return (
            f"E={east:+7.3f} N={north:+7.3f} U={up:+6.3f} | "
            f"vn={vn:+6.3f} ve={ve:+6.3f} vd={vd:+6.3f} | "
            f"lat={fix.latitude_deg_e7 / 1e7:.7f} lon={fix.longitude_deg_e7 / 1e7:.7f} "
            f"alt={fix.altitude_msl_mm / 1000.0:.2f} | "
            f"yaw={'--' if yaw is None else format(yaw, '.1f')} | "
            f"{sample.status or 'ok'} hacc={fix.horizontal_accuracy_mm / 1000.0:.2f}m "
            f"fix={FIX_TYPE_NAMES.get(fix.fix_type, fix.fix_type)} | "
            f"rx={self.received} tx={self.sent} on {key} | "
            f"from vehicle: {back or 'nothing yet'}"
        )


def _payload_bytes(sample) -> bytes:
    """zenoh-python returned bytes before 1.0 and a ZBytes after it."""
    payload = sample.payload
    if isinstance(payload, (bytes, bytearray)):
        return bytes(payload)
    to_bytes = getattr(payload, "to_bytes", None)
    return to_bytes() if callable(to_bytes) else bytes(payload)


# ──────────────────────────────────────────────────────────────────────────────
# Key construction
# ──────────────────────────────────────────────────────────────────────────────
def resolve_mode(mode: Optional[str], connect: Optional[str]) -> str:
    """Connecting to a known router is the textbook client-mode case; peer mode
    is for discovering whatever is on the local network."""
    return mode or ("client" if connect else "peer")


def zenoh_config(zenoh, connect: Optional[str], mode: str):
    config = zenoh.Config()
    config.insert_json5("mode", f'"{mode}"')
    if connect:
        config.insert_json5("connect/endpoints", f'["{connect}"]')
    return config


def build_key(args) -> str:
    if args.key:
        return args.key
    info = topic_catalog.topic_by_key(args.topic)
    parts = []
    if args.namespace:
        parts.append(args.namespace)
    parts.append(info.key)
    if info.multi_instance:
        # ** rather than * so a publisher that omits the instance segment
        # entirely still matches; the id inside the payload is what --instance
        # actually filters on.
        parts.append("**")
    return "/".join(parts)


# ──────────────────────────────────────────────────────────────────────────────
# Simulation source, so the whole chain can be exercised with no mocap
# ──────────────────────────────────────────────────────────────────────────────
# Only used to *produce* bytes; everything downstream decodes them through the
# synapse_fbs bindings like a real sample. --selftest checks this round trip,
# which is what keeps this hand-written layout honest.
SIM_EXTERNAL_ODOMETRY = struct.Struct("<Q3f4f3f3f4B")


def simulate_payload(t: float, radius: float, period: float, instance: int,
                     flags: Optional[int] = None, status: Optional[int] = None) -> bytes:
    angle = 2.0 * math.pi * (t / period)
    east, north, up = radius * math.cos(angle), radius * math.sin(angle), 1.5
    speed = 2.0 * math.pi * radius / period
    ve, vn, vu = -speed * math.sin(angle), speed * math.cos(angle), 0.0
    yaw = angle + math.pi / 2.0
    if flags is None:
        flags = (ExternalOdometryFlags.PositionValid | ExternalOdometryFlags.AttitudeValid
                 | ExternalOdometryFlags.LinearVelocityValid)
    if status is None:
        status = ExternalOdometryStatus.Filtered
    return SIM_EXTERNAL_ODOMETRY.pack(
        int(t * 1e6), east, north, up,
        math.cos(yaw / 2.0), 0.0, 0.0, math.sin(yaw / 2.0),
        ve, vn, vu, 0.0, 0.0, 2.0 * math.pi / period,
        flags, status, 0, instance)


