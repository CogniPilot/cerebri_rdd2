def cmd_list_topics() -> int:
    print(f"schema set {topic_catalog.SCHEMA_SET_HASH}")
    print(f"{'--topic':<16}{'id':>4}  {'payload':<32}{'size':>6}  note")
    for name, topic in input_topics().items():
        info = topic_catalog.topic_by_key(topic.key)
        size = info.payload_size if info.payload_size else "table"
        print(f"{name:<16}{info.id:>4}  {str(info.payload_type or info.root_table):<32}"
              f"{str(size):>6}  {topic.note}")
    return 0


def run(args) -> int:
    zenoh = None
    if not args.simulate:
        try:
            import zenoh  # noqa: F811  - checked before the serial port is opened
        except ImportError:
            return _die("eclipse-zenoh is required unless --simulate: pip install eclipse-zenoh")

    bridge = Bridge(args)
    period = 1.0 / args.rate
    session = None
    # Undeclared on garbage collection, so the handles have to outlive this
    # scope's setup block or the subscription silently stops delivering.
    subscribers = []

    if args.simulate:
        print("simulating a circular trajectory; no zenoh session")
    else:
        mode = resolve_mode(args.mode, args.connect)
        try:
            session = zenoh.open(zenoh_config(zenoh, args.connect, mode))
        except Exception as exc:
            return _die(f"cannot open a zenoh session in {mode} mode:\n  {exc}\n"
                        "       zenoh_scan.py reports what is reachable and what "
                        "is publishing.")

        key = build_key(args)
        subscribers.append(session.declare_subscriber(key, bridge.on_sample))
        print(f"subscribed to {key}")
        if args.covariance and args.topic == "external_pose":
            cov_key = build_key(argparse.Namespace(
                key=None, namespace=args.namespace, topic="external_pose_cov"))
            subscribers.append(session.declare_subscriber(cov_key, bridge.on_covariance))
            print(f"subscribed to {cov_key} for accuracy")

    print(f"origin {args.origin_lat:.7f} {args.origin_lon:.7f} alt={args.origin_alt:.1f} | "
          f"{args.rate} Hz | yaw_offset={args.yaw_offset:.1f}")

    last_log = time.monotonic()
    next_send = time.monotonic()
    try:
        while True:
            if args.simulate:
                t = time.monotonic() - bridge.start
                decoded = bridge.topic.decode(
                    simulate_payload(t, args.sim_radius, args.sim_period, args.instance or 0),
                    args.instance)
                if decoded is not None:
                    bridge.offer(decoded)

            result = bridge.tick()
            now = time.monotonic()
            if now - last_log >= 1.0:
                print(bridge.status_line(result) if result else
                      bridge.waiting_line(build_key(args)))
                last_log = now

            next_send += period
            # A long stall must not turn into a burst of catch-up frames.
            if next_send < now:
                next_send = now + period
            time.sleep(max(0.0, next_send - time.monotonic()))
    except KeyboardInterrupt:
        print()
    finally:
        subscribers.clear()
        if session is not None:
            session.close()

    print(f"received {bridge.received}, sent {bridge.sent}, "
          f"decode errors {bridge.decode_errors}")
    if bridge.from_vehicle:
        print("from vehicle: " + ", ".join(f"{k}={v}" for k, v in sorted(bridge.from_vehicle.items())))
    return 0


def _die(message: str) -> int:
    print(f"ERROR: {message}", file=sys.stderr)
    return 1


# ──────────────────────────────────────────────────────────────────────────────
# CLI
# ──────────────────────────────────────────────────────────────────────────────
def main() -> int:
    # Checked before the parser is built: the input-topic table names the
    # generated classes, so without them even --help would raise.
    if not HAVE_SYNAPSE_FBS:
        return _die("synapse-fbs is required: pip install synapse-fbs\n"
                    "       (the schema bindings from github.com/CogniPilot/synapse_fbs)")

    parser = argparse.ArgumentParser(
        description=__doc__.splitlines()[3],
        formatter_class=argparse.RawDescriptionHelpFormatter)

    parser.add_argument("--topic", default="external_pose", choices=sorted(input_topics()),
                        help="synapse catalog key to subscribe to (default: external_pose)")
    parser.add_argument("--namespace", default="**",
                        help="zenoh key namespace, e.g. cub1; default ** matches any")
    parser.add_argument("--key", default=None,
                        help="full key expression, overriding --namespace/--topic")
    parser.add_argument("--instance", type=int, default=None,
                        help="ExternalOdometryData.id, or the mocap rigid-body id")
    parser.add_argument("--connect", default=None,
                        help="zenoh router endpoint, e.g. tcp/192.168.1.10:7447")
    parser.add_argument("--mode", default=None, choices=("peer", "client"),
                        help="default: client when --connect is given, else peer")
    parser.add_argument("--no-covariance", dest="covariance", action="store_false",
                        help="ignore external_pose_cov and use --hacc/--vacc instead")
    parser.add_argument("--ignore-flags", action="store_true",
                        help="accept samples whose validity bits are clear, for producers "
                             "that fill the fields but never set the bitmask")

    parser.add_argument("--port", default="/dev/ttyUSB0", help="serial device (default: %(default)s)")
    parser.add_argument("--baud", type=int, default=57600, help="default: 57600 (SiK default)")
    parser.add_argument("--rate", type=float, default=10.0, help="Hz sent to the vehicle")
    parser.add_argument("--dry-run", action="store_true", help="decode and print, no serial port")
    parser.add_argument("--timeout", type=float, default=0.5,
                        help="seconds before a sample counts as stale (default: %(default)s)")

    parser.add_argument("--origin-lat", type=float, default=40.41545396897393)
    parser.add_argument("--origin-lon", type=float, default=-86.93275866259437)
    parser.add_argument("--origin-alt", type=float, default=0.0)
    parser.add_argument("--yaw-offset", type=float, default=230.0,
                        help="degrees the facility X axis is rotated from true north")
    parser.add_argument("--heading-offset", type=float, default=138.0)
    parser.add_argument("--publish-yaw", action="store_true",
                        help="set YawValid and send the attitude yaw")
    parser.add_argument("--hacc", type=float, default=0.05,
                        help="horizontal accuracy in metres when no covariance is available")
    parser.add_argument("--vacc", type=float, default=0.08)
    parser.add_argument("--degraded-scale", type=float, default=4.0,
                        help="accuracy multiplier while the producer reports degraded tracking")
    parser.add_argument("--hdop", type=float, default=0.3)
    parser.add_argument("--vdop", type=float, default=0.4)
    parser.add_argument("--satellites", type=int, default=14)
    parser.add_argument("--gnss-instance", type=int, default=0, help="GnssFixData.id")

    parser.add_argument("--simulate", action="store_true",
                        help="generate a circular trajectory instead of subscribing")
    parser.add_argument("--sim-radius", type=float, default=4.0, help="metres")
    parser.add_argument("--sim-period", type=float, default=20.0, help="seconds per lap")

    parser.add_argument("--selftest", action="store_true", help="check decoding and conversion")
    parser.add_argument("--list-topics", action="store_true", help="show the input topics")

    args = parser.parse_args()

    if args.selftest:
        return cmd_selftest()
    if args.list_topics:
        return cmd_list_topics()

    if topic_catalog.SCHEMA_SET_HASH != FIRMWARE_SCHEMA_SET_HASH:
        return _die(
            f"synapse-fbs schema set {topic_catalog.SCHEMA_SET_HASH} does not match the "
            f"{FIRMWARE_SCHEMA_SET_HASH} the firmware was built against.\n"
            "       Payload layouts may differ; the vehicle would report this as a "
            "climbing bad_len counter.")

    if args.simulate and args.topic != "external_pose":
        return _die("--simulate produces ExternalOdometryData, so it needs "
                    "--topic external_pose")

    return run(args)


if __name__ == "__main__":
    sys.exit(main())
